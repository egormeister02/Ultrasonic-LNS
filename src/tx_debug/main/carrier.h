#pragma once
//
// Непрерывная противофазная несущая 25 кГц на CARRIER_A_PIN / CARRIER_B_PIN (MCPWM).
// Гейтирование на пьезо делает аппаратно DWM1000 EXTTXE (ключи HC4066) — здесь несущая
// просто крутится без остановки, фаза к UWB не привязывается (приёмник детектирует
// огибающую, а не фазу).
//
#include "esp_err.h"

esp_err_t carrier_init(void);   // настроить MCPWM и запустить непрерывный противофазный меандр

// Сменить частоту несущей на лету. Период и 50%-скважность обновляются на границе периода
// (counter==0), поэтому фаза не срывается и оба выхода остаются строго противофазными.
esp_err_t carrier_set_freq(uint32_t hz);

// Запустить фоновую задачу подстройки частоты по делителю 0–3.3 В на АЦП (GPIO1 / ADC1_CH0):
// центр CARRIER_HZ, размах ±CARRIER_TRIM_HZ. Вызывать после carrier_init().
void carrier_start_freq_trim(void);
