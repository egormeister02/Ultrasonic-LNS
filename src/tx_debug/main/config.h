#pragma once
//
// Параметры передающего узла БПЛА (air_node) — АППАРАТНАЯ синхронизация УЗ ↔ UWB.
//
// Двухимпульсный пакет = ДВЕ UWB-передачи на цикл (вариант А):
//   импульс 1 — немедленная передача (dwm1000_send_immediate);
//   импульс 2 — Delayed-TX через ΔT после первой (dwt_setdelayedtrxtime). Разнос стартов
//   кадров (а значит и акустических пачек) фиксируется аппаратно DW1000 (~8 нс) -> ΔT кварцево-стабилен.
//
// Несущая 25 кГц крутится непрерывно на GPIO4/5. Каждый кадр поднимает GPIO5/EXTTXE (pad 10),
// который открывает ключи SN74HC4066 -> несущая проходит на пьезо ровно на время кадра
// (fine-grain TX-seq ВЫКЛючен -> EXTTXE = один чистый строб = эфирное время кадра, а не гребёнка).
//
//   импульс 1 (кадр 1, immediate)          импульс 2 (кадр 2, delayed +ΔT)
//      |‾‾‾‾‾‾|________ актив. ноль ________|‾‾‾‾‾‾|
//      <PULSE>      ключи разомкнуты         <PULSE>
//      <------------------ ΔT = DT_US = PULSE_US + GAP_US ------------------>
//

#define NODE_ID_AIR          1u   // идентификатор передающего узла (в кадрах PING/CONFIG/DATA)

// --- Флаги сборки ---
// ENABLE_ULTRASOUND: 0 = ЧИСТЫЙ UWB (несущую не запускаем, EXTTXE можно отключить) — диагностика,
//   проверяем, не УЗ-тракт ли портит UWB-кадр. 1 = штатный режим с аппаратной синхро-УЗ.
#define ENABLE_ULTRASOUND    1
// DEBUG_DWM: 1 = подробные init-логи + SPI-диагностика (deca_spi_diag). Продакшен = 0.
#define DEBUG_DWM            0

// ===========================================================================================
//                    ТАЙМИНГИ РАБОЧЕГО ЦИКЛА — вынесены в константы
// ===========================================================================================
//
// Частота несущей. Диапазон: задаётся резонансом пьезоизлучателя, практически 24.5–28 кГц
// (см. УЗ-драйвер анкера). Шаг: квазинепрерывный (MCPWM, период = 10 МГц / f; на 25 кГц
// шаг по f ≈ 60 Гц). Ставить в резонанс излучателя.
#define CARRIER_HZ       25000u

// Частота пакетов (пар импульсов). Диапазон: 1..10 Гц штатно. Шаг: 1 Гц.
//   ВЕРХ ограничен 10 Гц: при >10 Гц в воздухе оказывается более одной УЗ-пары и требуется
//   матчинг циклов по предсказаниям Калмана (bootstrap) — отдельная задача. 10 Гц безопасно при
//   любой дальности: БПЛА не смещается на десятки метров за 0.1 с -> циклы однозначны.
#define PACKET_RATE_HZ      10u

// Число импульсов в паре (двухимпульсная самокалибровка δ компаратора). Обычно 2.
#define PULSES_PER_PKT       2u

// --- Длительность ИМПУЛЬСА (= окно EXTTXE = эфирное время UWB-кадра) ---
//   Кадр = [преамбула PLEN2048 ≈ 2.03 мс (фикс)] + [SFD+PHR ≈ 0.24 мс (фикс)] + [данные].
//   Данные на 110 кбит/с ≈ 0.15 мс/байт (с учётом RS/свёрточного кода). Измерено: старый 5-байт
//   кадр (7 Б с CRC) -> ~3.1 мс. Длину импульса РЕГУЛИРУЕМ ДВУМЯ ручками:
//     * ГРУБО — преамбула PLEN (в dwm1000.c/_rx.c; ДОЛЖНА совпадать на обоих узлах; шаг ~×2);
//     * ТОЧНО — длиной полезной нагрузки DATA-кадра (паддинг), шаг ~0.15 мс/байт.
//
// DATA_PAYLOAD_LEN — полная полезная нагрузка DATA-кадра, байт.
//   Диапазон: 1 .. 125 (макс. кадр DW1000 = 127 Б вкл. 2 CRC). Шаг: 1 байт ≈ +0.15 мс импульса.
//   ОТЛАДКА (короткий импульс ~1 мс): преамбула укорочена до PLEN256 (см. dwm1000.c),
//   тогда фикс. часть ≈ преамбула(0.25 мс)+SFD+PHR(0.24 мс) ≈ 0.49 мс, и
//   длина импульса(N) ≈ 0.49 мс + (N+2)·0.15 мс. При N=2 → ~1.09 мс. Точное значение —
//   МЕРИТЬ ОСЦИЛЛОГРАФОМ и подгонять N по факту (±1 байт ≈ ±0.15 мс).
#define DATA_PAYLOAD_LEN     2u

// PULSE_US_NOM — НОМИНАЛ длительности импульса (реальная задаётся PLEN+паддингом, см. выше) —
//   перемерить осциллографом и привести в соответствие с DATA_PAYLOAD_LEN.
#define PULSE_US_NOM      1000u

// GAP_US_NOM — НОМИНАЛ акустического зазора между импульсами.
//   Снизу: ≳ ringdown пьезо (~1 мс). Реальный зазор = DT_US − реальная_длина_импульса.
#define GAP_US_NOM        2000u

// DT_US — разнос СТАРТОВ двух импульсов (программируется Delayed-TX). Шаг ~8 нс (практически
//   непрерывно, ТОЧНО). ВАЖНО: DT_US должен быть > реальной длины импульса, иначе два окна EXTTXE
//   сольются. Сверху: < периода пакета (1000/PACKET_RATE_HZ мс). Диапазон ~ (имп+1 мс)..(период−имп).
#define DT_US            (PULSE_US_NOM + GAP_US_NOM)   // = 3000 мкс

// --- Производные ---
#define PACKET_PERIOD_MS  (1000u / (PACKET_RATE_HZ))
// Единица системного времени DWM1000 = 1/(499.2 МГц × 128) ≈ 15.65 пс => 63897.6 ед/мкс
#define DWT_TICKS_PER_US  63898ULL
#define DT_TICKS          ((uint64_t)DT_US * DWT_TICKS_PER_US)
